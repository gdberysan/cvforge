/**
 * Bundles drizzle/*.sql into lib/db/wasm/migrations.gen.ts for the web
 * edition, which has no filesystem to read them from. Same shape and hash as
 * drizzle's own readMigrationFiles, so both editions record identical rows in
 * __drizzle_migrations. `npm run db:bundle` after `db:generate`; a test fails
 * when the bundle is stale.
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { readMigrationFiles } from 'drizzle-orm/migrator'

const out = path.join('lib', 'db', 'wasm', 'migrations.gen.ts')
const migrations = readMigrationFiles({ migrationsFolder: 'drizzle' })
writeFileSync(
  out,
  `// Generated by scripts/bundle-migrations.ts from drizzle/. Do not edit.\nimport type { MigrationMeta } from 'drizzle-orm/migrator'\n\nexport const MIGRATIONS: MigrationMeta[] = ${JSON.stringify(migrations, null, 1)}\n`,
)
console.log(`bundled ${migrations.length} migrations into ${out}`)
