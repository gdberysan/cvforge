/**
 * Locks the built web edition down (runs after `next build web`). The page
 * holds the person's Anthropic key, so the browser is told exactly what may
 * run and where anything may go:
 *
 * - Each HTML file gets its own Content-Security-Policy <meta>, first in
 *   <head>: scripts only from this origin plus the exact inline scripts Next
 *   wrote into that file (sha256), no eval, no plugins, forms only to self,
 *   network only to self. Per file because the inline scripts differ by
 *   page, and a header carrying every page's hashes would outgrow the host's
 *   limits.
 * - web/out/_headers (Cloudflare Pages) carries what a <meta> cannot: who
 *   may frame the site (itself and the CVForge extension), and the Worker's
 *   own policy — the only place Anthropic is reachable and WebAssembly may
 *   compile (the database).
 *
 * Fails the build if a page has an inline script it cannot hash.
 */
import { createHash } from 'node:crypto'
import { globSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const OUT = path.join('web', 'out')
const ANTHROPIC = 'https://api.anthropic.com'

/** The page's own policy, given its inline scripts' hashes. */
export function pagePolicy(hashes: string[]): string {
  return [
    "default-src 'self'",
    `script-src 'self' ${hashes.map((h) => `'sha256-${h}'`).join(' ')}`.trim(),
    // React style props and next/font: inline styles only, never scripts.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' blob: data:",
    "font-src 'self' data:",
    // The page talks to its own Worker and files; the key never leaves from
    // here. Google Drive only when the person connects it (web/lib/drive.ts):
    // the Drive API and the token-revoke endpoint, nothing else of Google's.
    "connect-src 'self' https://www.googleapis.com https://oauth2.googleapis.com",
    "worker-src 'self'",
    "manifest-src 'self'",
    // CV preview and print are srcdoc frames of our own HTML.
    "frame-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
  ].join('; ')
}

/** The Worker: the database (WebAssembly) and the one call out, to Anthropic. */
export const WORKER_POLICY = [
  "default-src 'none'",
  "script-src 'self' 'wasm-unsafe-eval'",
  `connect-src 'self' ${ANTHROPIC}`,
].join('; ')

const INLINE = /<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g

export function inlineHashes(html: string): string[] {
  const hashes = new Set<string>()
  for (const m of html.matchAll(INLINE)) {
    const attrs = m[1] ?? ''
    // JSON and other data blocks are never executed; they need no hash.
    if (/type="(application\/(ld\+)?json|text\/x-[^"]*)"/.test(attrs)) continue
    hashes.add(
      createHash('sha256')
        .update(m[2] ?? '', 'utf8')
        .digest('base64'),
    )
  }
  return [...hashes]
}

export function withPolicy(html: string): string {
  const meta = `<meta http-equiv="Content-Security-Policy" content="${pagePolicy(inlineHashes(html))}">`
  const at = html.indexOf('<head>')
  if (at < 0) throw new Error('no <head> to put the policy in')
  return `${html.slice(0, at + 6)}${meta}${html.slice(at + 6)}`
}

const HEADERS = `# Generated by scripts/web-csp.ts. Cloudflare Pages.
/*
  Content-Security-Policy: frame-ancestors 'self' chrome-extension:
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Cross-Origin-Opener-Policy: same-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()

/worker/*
  Content-Security-Policy: ${WORKER_POLICY}

/sw.js
  Content-Security-Policy: default-src 'self'
  Service-Worker-Allowed: /

/build.json
  Cache-Control: no-cache
`

if (process.argv[1]?.endsWith('web-csp.ts')) {
  const files = globSync(path.join(OUT, '**', '*.html'))
  if (files.length === 0) throw new Error(`no HTML in ${OUT}: build first`)
  for (const file of files) {
    const html = readFileSync(file, 'utf8')
    if (html.includes('http-equiv="Content-Security-Policy"')) continue
    writeFileSync(file, withPolicy(html))
  }
  writeFileSync(path.join(OUT, '_headers'), HEADERS)
  console.log(`csp: ${files.length} pages, _headers written`)
}
