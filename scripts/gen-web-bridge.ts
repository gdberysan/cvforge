/**
 * Generates the web edition's bridge to the desktop's server code, so the
 * same components and the same actions/routes run in the browser:
 *
 * - web/worker/registry.gen.ts — the Worker imports every portable action
 *   module and route handler (desktop files, unchanged, through the shims in
 *   web/worker/shims) plus the web edition's own replacements, by key.
 * - web/actions/<key>.ts — page-side stand-ins with the same export names:
 *   each action becomes a call to the Worker, or, for a desktop-only module
 *   the web edition does not replace, a typed refusal (so the components
 *   that import it still build; the web never shows them).
 * - web/actions/aliases.gen.json — desktop module path -> stand-in, read by
 *   web/next.config.ts.
 *
 * Run `npm run web:bridge` after adding or renaming an action or route; a
 * test fails when the output is stale.
 */
import { globSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

// The job agent's actions (any agent-actions file, app/(app)/agent/) never
// reach the browser: the agent is private and the web edition has none.
export const DESKTOP_ONLY =
  /app\/api\/(export\/pdf|export\/backup|import\/backup|shutdown|push\/|kit\/)|app\/\(app\)\/(settings|agent|discover)\/actions|agent-actions/

/**
 * Desktop-only action modules the web edition replaces with its own
 * implementation (same key, same export names for what it keeps).
 */
export const WEB_OVERRIDES: Record<string, string> = {
  'app/(app)/settings/actions.ts': 'web/worker/actions/settings.ts',
}

/** Desktop-only routes the web edition answers with its own handler. */
export const WEB_ROUTE_OVERRIDES: Record<string, string> = {
  'app/api/export/pdf/route.ts': 'web/worker/routes/export-pdf.ts',
}

const allActionFiles = globSync('app/**/*actions.ts').sort()
const actionFiles = allActionFiles.filter((f) => !DESKTOP_ONLY.test(f))
const refusedFiles = allActionFiles.filter((f) => DESKTOP_ONLY.test(f) && !(f in WEB_OVERRIDES))
const routeFiles = globSync('app/api/**/route.ts')
  .filter((f) => !DESKTOP_ONLY.test(f))
  .sort()

/**
 * "app/(app)/evidence/import/actions.ts" -> "evidence/import";
 * "app/(app)/application/[id]/people-actions.ts" -> "application/id/people-actions"
 */
const keyOf = (file: string) =>
  file
    .replace(/^app\/\(app\)\//, '')
    .replace(/\/actions\.ts$/, '')
    .replace(/\.ts$/, '')
    .replace(/[[\]]/g, '')
/** "app/api/ai/triage/route.ts" -> "/api/ai/triage" */
const routeOf = (file: string) => `/${file.replace(/^app\//, '').replace(/\/route\.ts$/, '')}`
const spec = (file: string) => `@/${file.replace(/\.ts$/, '')}`
const standInOf = (key: string) => `web/actions/${key.replace(/\//g, '__')}.ts`

const header = '// Generated by scripts/gen-web-bridge.ts. Do not edit.\n'

function exportsOf(file: string): { fns: string[]; types: string[] } {
  const source = readFileSync(file, 'utf8')
  return {
    fns: [...source.matchAll(/^export async function (\w+)/gm)].map((m) => m[1] as string),
    types: [...source.matchAll(/^export type (\w+)/gm)].map((m) => m[1] as string),
  }
}

function standIn(impl: string, body: (fn: string) => string, importLine: string): string {
  const { fns, types } = exportsOf(impl)
  const rel = path.relative('web/actions', impl).replace(/\.ts$/, '')
  return [
    header,
    importLine,
    `import type * as desktop from '${rel}'`,
    ...(types.length ? [`export type { ${types.join(', ')} } from '${rel}'`] : []),
    '',
    ...fns.map(body),
    '',
  ].join('\n')
}

export function generate(): Record<string, string> {
  const out: Record<string, string> = {}
  const aliases: Record<string, string> = {}
  const overrides = Object.entries(WEB_OVERRIDES).sort()
  const routeOverrides = Object.entries(WEB_ROUTE_OVERRIDES).sort()

  out['web/worker/registry.gen.ts'] = [
    header,
    ...actionFiles.map((f, i) => `import * as a${i} from '${spec(f)}'`),
    ...overrides.map(([, web], i) => `import * as w${i} from '${spec(web)}'`),
    ...routeFiles.map((f, i) => `import * as r${i} from '${spec(f)}'`),
    ...routeOverrides.map(([, web], i) => `import * as wr${i} from '${spec(web)}'`),
    '',
    '// biome-ignore lint/suspicious/noExplicitAny: an action takes whatever its form sends',
    'type Fn = (...args: any[]) => unknown',
    '',
    'export const ACTIONS: Record<string, Record<string, Fn>> = {',
    ...actionFiles.map((f, i) => `  '${keyOf(f)}': a${i} as unknown as Record<string, Fn>,`),
    ...overrides.map(([desk], i) => `  '${keyOf(desk)}': w${i} as unknown as Record<string, Fn>,`),
    '}',
    '',
    'export const ROUTES: Record<string, Record<string, Fn>> = {',
    ...routeFiles.map((f, i) => `  '${routeOf(f)}': r${i} as unknown as Record<string, Fn>,`),
    ...routeOverrides.map(
      ([desk], i) => `  '${routeOf(desk)}': wr${i} as unknown as Record<string, Fn>,`,
    ),
    '}',
    '',
  ].join('\n')

  const bridged: [desktop: string, impl: string][] = [
    ...actionFiles.map((f): [string, string] => [f, f]),
    ...overrides,
  ]
  for (const [file, impl] of bridged) {
    const key = keyOf(file)
    out[standInOf(key)] = standIn(
      impl,
      (fn) =>
        `export const ${fn}: typeof desktop.${fn} = (...args) =>\n  callAction('${key}', '${fn}', args) as ReturnType<typeof desktop.${fn}>`,
      "import { callAction } from '@/web/lib/actions-client'",
    )
    aliases[spec(file)] = `./${path.relative('web', standInOf(key))}`
  }
  for (const file of refusedFiles) {
    const key = keyOf(file)
    out[standInOf(key)] = standIn(
      file,
      (fn) =>
        `export const ${fn}: typeof desktop.${fn} = () =>\n  notInBrowser('${key}', '${fn}') as ReturnType<typeof desktop.${fn}>`,
      "import { notInBrowser } from '@/web/lib/actions-client'",
    )
    aliases[spec(file)] = `./${path.relative('web', standInOf(key))}`
  }
  out['web/actions/aliases.gen.json'] = `${JSON.stringify(aliases, null, 2)}\n`
  return out
}

if (process.argv[1]?.endsWith('gen-web-bridge.ts')) {
  mkdirSync('web/actions', { recursive: true })
  const files = generate()
  for (const [file, text] of Object.entries(files)) writeFileSync(file, text)
  console.log(
    `web bridge: ${actionFiles.length} action modules, ${Object.keys(WEB_OVERRIDES).length} web replacements, ${refusedFiles.length} desktop-only refused, ${routeFiles.length} routes + ${Object.keys(WEB_ROUTE_OVERRIDES).length} web routes`,
  )
}
